const live: Live = svg => {
  const fl = q(svg, ".fl")!, bub = bubbles(svg, 9, 23, 56, 50, 6, "rgba(255,240,220,.6)", .8);
  return s => {
    const t = s.t * (s.calm ? .4 : 1), a = s.calm ? .4 : 1;
    fl.setAttribute("transform", `translate(16 62) skewX(${(a * 5 * Math.sin(t * 4.3)).toFixed(2)}) scale(1 ${(1 + a * .1 * Math.sin(t * 9.1)).toFixed(3)}) translate(-16 -62)`);
    bub(s);
  };
};

