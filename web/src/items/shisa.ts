import { poly, tone, puff, ngon } from "./lowpoly";
import type { ItemDef } from "./types";

function art() {
  const T = tone("#b8643e"), K = "#2a1c16";
  const curl = (cx: number, cy: number, r: number) => puff(T, ngon(cx, cy, r, 6), [cx - r * .3, cy - r * .3]);
  return `${poly(T.deep, [[4, 50], [38, 50], [37, 52], [5, 52]])}
    ${poly(T.mid, [[8, 50], [8, 30], [14, 24], [30, 24], [34, 32], [34, 50]])}${poly(T.lo, [[24, 24], [30, 24], [34, 32], [34, 50], [24, 50]])}
    ${poly(T.hi, [[10, 40], [16, 40], [16, 50], [10, 50]])}${poly(T.lo, [[26, 40], [32, 40], [32, 50], [26, 50]])}
    ${curl(6, 14, 5)}${curl(8, 24, 5)}${curl(34, 14, 5)}${curl(32, 24, 5)}${curl(12, 6, 5)}${curl(28, 6, 5)}${curl(20, 4, 5)}
    ${puff(T, [[10, 10], [20, 6], [30, 10], [32, 22], [26, 30], [14, 30], [8, 22]], [16, 14])}
    ${poly("#e8e0cc", [[13, 14], [17, 13], [17, 16.4], [13, 16.6]])}${poly("#e8e0cc", [[23, 13], [27, 14], [27, 16.6], [23, 16.4]])}
    ${poly(K, [[15, 14], [17, 13.6], [17, 16], [15, 16.2]])}${poly(K, [[23, 13.6], [25, 14], [25, 16.2], [23, 16]])}
    ${poly(T.deep, [[17, 19], [23, 19], [21, 21], [19, 21]])}
    ${poly(K, [[12, 23], [28, 23], [25, 28], [15, 28]])}${poly("#e8e0cc", [[13, 23], [15, 23], [14, 25]])}${poly("#e8e0cc", [[25, 23], [27, 23], [26, 25]])}`;
}

export default { key: "shisa", label: "シーサー", at: "shelf", w: 40, h: 52, cat: "飾り", order: 612, region: "JP-47", note: "沖縄で。口を開けた方", art } satisfies ItemDef;
